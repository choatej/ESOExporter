-- The framework's own assertions: a failing assertion must actually fail.

describe("assertions", function()
    it("eq compares tables deeply", function()
        eq({ 1, { a = true } }, { 1, { a = true } })
        raises(function()
            eq({ 1 }, { 2 })
        end, "expected")
    end)

    it("eq notices extra keys on either side", function()
        raises(function()
            eq({ a = 1 }, { a = 1, b = 2 })
        end)
        raises(function()
            eq({ a = 1, b = 2 }, { a = 1 })
        end)
    end)

    it("truthy and falsy", function()
        truthy(0)
        falsy(nil)
        raises(function()
            truthy(false)
        end)
        raises(function()
            falsy(1)
        end)
    end)

    it("raises checks the message when given one", function()
        raises(function()
            error("boom")
        end, "boom")
        raises(function()
            raises(function()
                error("boom")
            end, "other")
        end, "does not contain")
        raises(function()
            raises(function() end)
        end, "succeeded")
    end)
end)

describe("hooks", function()
    local counter = 0
    before_each(function()
        counter = counter + 1
    end)

    it("runs before each test", function()
        eq(counter, 1)
    end)

    it("runs again for the next test", function()
        eq(counter, 2)
    end)
end)
